-- DATA-011A: National Dataset Catalogue — extend government_datasets (no parallel table).
-- Catalogue is the system of record for trusted dataset acquisition metadata.
-- RIC acquires/stages; Platform publishes only via Admin API after human review.
-- Does not auto-enable fetch or invent importers.

ALTER TABLE government_datasets
    ADD COLUMN jurisdiction VARCHAR(80) NULL AFTER coverage,
    ADD COLUMN source_url VARCHAR(1000) NULL AFTER endpoint_url,
    ADD COLUMN source_format VARCHAR(40) NULL AFTER fetch_method,
    ADD COLUMN update_frequency VARCHAR(80) NULL AFTER source_format,
    ADD COLUMN last_downloaded_at DATETIME NULL AFTER last_checked_at,
    ADD COLUMN record_count INT UNSIGNED NULL AFTER last_imported_at,
    ADD COLUMN auto_update_enabled TINYINT(1) NOT NULL DEFAULT 0 AFTER is_enabled,
    ADD COLUMN catalogue_status ENUM('planned','indexed','active','paused','retired') NOT NULL DEFAULT 'planned' AFTER auto_update_enabled,
    ADD COLUMN duplicate_rules_json JSON NULL AFTER record_types_json,
    ADD COLUMN notes TEXT NULL AFTER last_error;

-- Backfill jurisdiction from coverage where empty.
UPDATE government_datasets
SET jurisdiction = CASE
    WHEN coverage LIKE 'AU national%' OR coverage = 'AU' OR coverage LIKE 'AU %' THEN 'AU'
    WHEN coverage LIKE 'QLD%' THEN 'QLD'
    WHEN coverage LIKE 'NSW%' THEN 'NSW'
    WHEN coverage LIKE 'VIC%' THEN 'VIC'
    WHEN coverage LIKE 'SA%' THEN 'SA'
    WHEN coverage LIKE 'WA%' THEN 'WA'
    WHEN coverage LIKE 'TAS%' THEN 'TAS'
    WHEN coverage LIKE 'ACT%' THEN 'ACT'
    WHEN coverage LIKE 'NT%' THEN 'NT'
    ELSE jurisdiction
END
WHERE jurisdiction IS NULL AND coverage IS NOT NULL;

UPDATE government_datasets
SET source_url = endpoint_url
WHERE source_url IS NULL AND endpoint_url IS NOT NULL AND endpoint_url <> '';

UPDATE government_datasets
SET catalogue_status = CASE WHEN is_enabled = 1 THEN 'active' ELSE 'indexed' END
WHERE catalogue_status = 'planned'
  AND dataset_key IN (
      'au_national_public_toilet_map',
      'au_national_toilet_map_dump_points',
      'demo_geojson_dump_points',
      'demo_csv_public_toilets',
      'demo_csv_drinking_water',
      'demo_csv_rest_areas',
      'demo_csv_visitor_information'
  );

